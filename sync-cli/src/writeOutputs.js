import { writeFileSync, mkdirSync, copyFileSync, symlinkSync, existsSync, unlinkSync, lstatSync } from "node:fs";
import path from "node:path";

const GENERATED_HEADER = (otterVersion, stackName) => `<!--
  Generated by @otter/sync-cli from otter ${otterVersion}, stack ${stackName}.
  Do not edit this file directly — edit the layer it came from (org/, the
  stack pack, or this repo's local instructions) and re-run the sync.
-->
`;

// Best-effort mapping from abstract guardrail labels to Claude Code
// permission rule syntax. This is a first draft: validate it against current
// Claude Code permission docs before treating it as the sole enforcement for
// a guardrail — some labels (e.g. "production-credentials") can't be
// expressed as a tool pattern and need a different control.
const DENY_PATTERNS = {
  "destructive-commands": ["Bash(rm -rf *)", "Bash(git push --force*)", "Bash(git reset --hard*)"],
};
const ASK_PATTERNS = {
  "dependency-installs": ["Bash(npm install*)", "Bash(npm ci*)"],
  "changes-to-ci-config": ["Edit(.github/workflows/**)", "Write(.github/workflows/**)"],
};

export function renderAgentsMd(merged, { otterVersion, stackName }) {
  const body = merged.instructionSections
    .map((s) => `## ${s.label}\n\n${s.text}`)
    .join("\n\n---\n\n");
  return GENERATED_HEADER(otterVersion, stackName) + "\n" + body + "\n";
}

export function renderClaudeSettings(merged) {
  const deny = merged.guardrails.deny.flatMap((label) => DENY_PATTERNS[label] ?? []);
  const ask = [
    ...merged.guardrails.require_approval.flatMap((label) => ASK_PATTERNS[label] ?? []),
    ...merged.guardrails.protected_paths.flatMap((p) => [`Edit(${p}**)`, `Write(${p}**)`]),
  ];
  return {
    permissions: { deny, ask },
    // Traceability: the abstract labels these rules were generated from.
    otter: {
      guardrails: merged.guardrails,
    },
  };
}

export function writeOutputs(merged, { repoPath, otterVersion, stackName }) {
  const agentsPath = path.join(repoPath, "AGENTS.md");
  writeFileSync(agentsPath, renderAgentsMd(merged, { otterVersion, stackName }));

  const claudePath = path.join(repoPath, "CLAUDE.md");
  if (existsSync(claudePath) || isSymlink(claudePath)) unlinkSync(claudePath);
  symlinkSync("AGENTS.md", claudePath);

  const claudeDir = path.join(repoPath, ".claude");
  mkdirSync(claudeDir, { recursive: true });
  writeFileSync(
    path.join(claudeDir, "settings.json"),
    JSON.stringify(renderClaudeSettings(merged), null, 2) + "\n",
  );

  const skillsDir = path.join(claudeDir, "skills");
  mkdirSync(skillsDir, { recursive: true });
  for (const skill of merged.skills) {
    copyFileSync(skill.path, path.join(skillsDir, `${skill.namespace}-${skill.name}.md`));
  }

  return {
    files: [agentsPath, claudePath, path.join(claudeDir, "settings.json"), skillsDir],
  };
}

function isSymlink(p) {
  try {
    return lstatSync(p).isSymbolicLink();
  } catch {
    return false;
  }
}
